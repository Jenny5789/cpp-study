/* 부동 소수점 표현에서 오류가 발생하는 경우를 찾으세요 */
#include <iostream>
using namespace std;

main()
{
    //변수 선언
    float a = 0.0712F;
    float b = 6.0712;
    float c = 1.234E2;
    float d = 1123E-2;    
    
    
    //문구 출력 & 결과 출력
    cout << "a= " << a << endl;
    cout << "b= " << b << endl;
    cout << "c= " << c << endl;
    cout << "d= " << d << endl;

    return 0;

}


/*🧐 
* F로 명시되어 부동소수점이 오류 없이 나올거라 예상
* 1.234E2는 1.234*10^2이 계산되어 123.4로 예상
* 소수점 없이 '1123E-2'로 적어' 오류 예상 */


/* 📜 부동소수점 표현 및 생략 규칙.
* 기본 형식: 정수부 + 소수점(.) + 소수부
* 0 생략 규칙: 소수점 앞 0 생략(0.5-->.5)/ 소수점 뒤 0 생략(10.0-->10.)
* 지수 표기법(과학적 표기법): E지수(10^지수) 사용(1.23e4--> 1.23*10^4)
* E 앞에 소수점이 없어도 E 가 붙어 있으면 지수(E)를 의미함(1123E-2 --> 11.23)


*/